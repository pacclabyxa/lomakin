// Товары не меняются во время работы приложения, поэтому генерируем их один раз на уровне модуля — вне компонентов.
export const products = Array.from({ length: 5000 }, (_, i) => ({
  id: i + 1,
  title: `Товар ${i + 1}`,
  price: 100 + (i % 50) * 10,
  // Каждый третий — не в наличии (i = 0, 3, 6...)
  inStock: i % 3 !== 0,
}));